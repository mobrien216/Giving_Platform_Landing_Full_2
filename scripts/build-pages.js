#!/usr/bin/env node
/* ============================================================
   build-pages.js — generates the Community and Advisor app pages
   from one shared template. No dependencies; Node 16+.

     node scripts/build-pages.js           write community/ and advisors/index.html
     node scripts/build-pages.js --check   exit 1 if either page is out of date
                                           (use before committing / in CI)

   Sources (edit these, never the generated pages):
     src/giving/page.html       the shared page. Contains
                                  {{title}}               inline placeholder
                                  <!-- @slot name -->     on a line of its own
     src/giving/<app>.html      that app's fills: one block per slot,
                                  <!-- @fill name -->
                                  …lines, copied verbatim (indentation included)…
                                Anything before the first @fill is a comment
                                for humans and is ignored.

   Rules (enforced, the build fails otherwise):
     · every slot in the template has exactly one fill in every app, and
       every fill matches a slot — a typo can't silently drop markup
     · an empty fill removes the slot line entirely
     · fills are copied byte-for-byte, so output is predictable to diff
   ============================================================ */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'src', 'giving');
const TEMPLATE = path.join(SRC, 'page.html');
const APPS = [
  { name: 'community', fills: path.join(SRC, 'community.html'), out: path.join(ROOT, 'community', 'index.html') },
  { name: 'advisors',  fills: path.join(SRC, 'advisors.html'),  out: path.join(ROOT, 'advisors',  'index.html') },
];
const BANNER = '<!-- GENERATED by scripts/build-pages.js from src/giving/ — do not edit this file. Edit the source, then run: node scripts/build-pages.js -->';

const SLOT_RE = /^\s*<!-- @slot ([a-z0-9-]+) -->\s*$/;
const FILL_RE = /^<!-- @fill ([a-z0-9-]+) -->$/;

function fail(msg){ console.error('build-pages: ' + msg); process.exit(1); }
function lines(file){
  const text = fs.readFileSync(file, 'utf8');
  if (text.includes('\r')) fail(path.relative(ROOT, file) + ' has CRLF line endings; save it with LF.');
  return text.split('\n');
}

/* <!-- @fill name --> blocks → Map(name → array of lines) */
function parseFills(file){
  const src = lines(file);
  if (src[src.length - 1] === '') src.pop();          // the file's final newline
  const fills = new Map();
  let current = null;
  for (const line of src){
    const m = line.match(FILL_RE);
    if (m){
      if (fills.has(m[1])) fail(path.relative(ROOT, file) + ': @fill ' + m[1] + ' appears twice.');
      current = m[1]; fills.set(current, []);
    } else if (current){
      fills.get(current).push(line);
    }
  }
  return fills;
}

function render(templateLines, fills, appName){
  const used = new Set();
  const title = fills.get('title');
  if (!title || !title.join('').trim()) fail(appName + ': missing @fill title.');
  used.add('title');

  const out = [];
  for (const line of templateLines){
    const m = line.match(SLOT_RE);
    if (m){
      const name = m[1];
      if (!fills.has(name)) fail(appName + ': template slot "' + name + '" has no @fill.');
      if (used.has(name)) fail('template uses slot "' + name + '" more than once.');
      used.add(name);
      out.push(...fills.get(name));
    } else {
      out.push(line.split('{{title}}').join(title.join(' ').trim()));
    }
  }
  for (const name of fills.keys()) if (!used.has(name)) fail(appName + ': @fill "' + name + '" has no matching slot in the template.');

  if (!/^<!DOCTYPE html>/i.test(out[0])) fail('template must start with <!DOCTYPE html>.');
  out.splice(1, 0, BANNER);
  return out.join('\n');
}

const check = process.argv.includes('--check');
const template = lines(TEMPLATE);
let stale = 0;
for (const app of APPS){
  const html = render(template, parseFills(app.fills), app.name);
  const rel = path.relative(ROOT, app.out).replace(/\\/g, '/');
  const current = fs.existsSync(app.out) ? fs.readFileSync(app.out, 'utf8') : null;
  if (check){
    if (current !== html){ console.error('out of date: ' + rel); stale++; }
    else console.log('up to date: ' + rel);
  } else if (current === html){
    console.log('unchanged:  ' + rel);
  } else {
    fs.writeFileSync(app.out, html);
    console.log('wrote:      ' + rel);
  }
}
if (stale) fail(stale + ' page(s) out of date — run: node scripts/build-pages.js');
